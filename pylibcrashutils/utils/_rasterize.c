int bitset_count[8] = { 0, 1, 1, 2, 1, 2, 2, 3 };
int bitset_vert_idx[8] = { -1, 2, 1, 0, 0, 1, 2, -1 };
int bitset_inside_idxs[8][2] =   { { -1, -1 }, { 2, -1 }, { 1, -1 }, { 1, 2 }, 
    {  0, -1 }, { 0,  2 }, { 0,  1 }, { -1, -1 } };
int bitset_others_idxs[8][2] =   { { -1, -1 }, { 0, 1 }, { 0, 2 }, { 1, 2 }, 
    {  1,  2 }, { 0, 2 }, { 0, 1 }, { -1, -1 } };
float edge_values[4] = { -1.0, 1.0, -1.0, 1.0 };

inline static int test_poly(fpoly *poly, int edge) {
  int i, bits;
  fpnt *vert;
  
  bits = 0;
  switch (edge) {
  case 0:
    for (i=0;i<3;i++) {
      vert = &poly->verts[i];  
      if (vert->x >= edge_values[0])
        bits |= 1;
      bits <<= 1;
    }
    break;
  case 1:
    for (i=0;i<3;i++) {
      vert = &poly->verts[i];
      if (vert->x <= edge_values[1])
        bits |= 1;
      bits <<= 1;
    }
    break;
  case 2:
    for (i=0;i<3;i++) {
      vert = &poly->verts[i];
      if (vert->y >= edge_values[2])
        bits |= 1;
      bits <<= 1;
    }
    break;
  case 3:
    for (i=0;i<3;i++) {
      vert = &poly->verts[i];
      if (vert->y <= edge_values[3])
        bits |= 1;
      bits <<= 1;
    }
    break;
  }
  bits >>= 1;
  return bits;
}

inline static int is_valid_poly(fpoly *poly) {
  int i;
  for (i=0;i<3;i++) {
    if (poly->verts[i].x == poly->verts[(i+2)%3].x &&
        poly->verts[i].y == poly->verts[(i+2)%3].y)
      return 0;
    if ((poly->verts[i].x != poly->verts[i].x) ||
        (poly->verts[i].y != poly->verts[i].y))
      return 0;
  }
  return 1;
}
  
#define swap(a,b) do { tmp=a; a=b; b=tmp; } while(0);
#define swap_poly_xy(poly) do { swap(poly->verts[0].x,poly->verts[0].y) swap(poly->verts[1].x,poly->verts[1].y) swap(poly->verts[2].x,poly->verts[2].y) } while (0);

#define print_poly(poly) for (vi=0;vi<3;vi++) {   printf("vert %i: (x: %f, y: %f, z: %f)\n", vi,     (poly)->verts[vi].x, (poly)->verts[vi].y, (poly)->verts[vi].z); }

/**
 * clips a poly at the first viewport edge with which it intersects, if
 * any. 
 *
 * the result polys themselves may still intersect the viewport; 
 * therefore it may be necessary to recursively call this function on 
 * results to get the complete set of polys (i.e. triangles) which cover
 * the original 'clipped poly'
 *
 * returns: -1 if poly is rejected
 *           0 if no clipping necessary
 *           1 if poly is clipped
 */
inline static int clip_poly(fpoly *src_poly, fpoly *dst_polys,
                             int *poly_count) {
  int i, ii, idx, bits, count;
  fpnt new_verts[4], new_vertuvws[4];
  int new_vert_count;
  fpnt *vert, *other, *new_vert;
  fpnt *vertuvw, *otheruvw, *new_vertuvw;
  float val, t, xy, z, w, tmp;
  fpoly *new_poly;
  int vi;
  
  *poly_count = 0;
  for (i=0;i<4;i++) {
    bits = test_poly(src_poly, i);
    count = bitset_count[bits];
    if (count == 3) continue; // if all 3 on inside, then try next edge
    else if (count == 0) return -1; // all outside, so reject
    new_vert_count = 0;
    for (ii=0;ii<2;ii++) {
      idx = bitset_inside_idxs[bits][ii];
      if (idx == -1) break;
      new_verts[new_vert_count] = src_poly->verts[idx];
      new_vertuvws[new_vert_count] = src_poly->vertuvws[idx];
      new_vert_count++;
    }
    if (i >= 2) { // top or bottom edge
      swap_poly_xy(src_poly);
    }
    val = edge_values[i];
    vert = &src_poly->verts[bitset_vert_idx[bits]];
    vertuvw = &src_poly->vertuvws[bitset_vert_idx[bits]];
    for (ii=0;ii<2;ii++) { 
      idx = bitset_others_idxs[bits][ii];
      other = &src_poly->verts[idx];
      otheruvw = &src_poly->vertuvws[idx];
      t = (val-vert->x)/(other->x-vert->x);
      xy = vert->y + t*(other->y-vert->y);
      z = vert->z + t*(other->z-vert->z);
      w = vertuvw->z + t*(otheruvw->z-vertuvw->z);
      new_vert = &new_verts[new_vert_count];
      new_vertuvw = &new_vertuvws[new_vert_count];
      new_vert->x = i>=2 ? xy : val;
      new_vert->y = i>=2 ? val: xy;
      new_vert->z = z;
      new_vertuvw->z = w;
      new_vert_count++;
    }
    if (i >= 2) { // top or bottom edge
      swap_poly_xy(src_poly);
    }
    new_poly = &dst_polys[(*poly_count)];
    for (ii=0;ii<3;ii++) {
      new_poly->verts[ii] = new_verts[ii];
      new_poly->vertuvws[ii] = new_vertuvws[ii];
    }
    if (is_valid_poly(new_poly)) (*poly_count)++; 
    if (new_vert_count > 3) {
      new_poly = &dst_polys[(*poly_count)];
      for (ii=0;ii<3;ii++) {
        new_poly->verts[ii] = new_verts[ii+1];
        new_poly->vertuvws[ii] = new_vertuvws[ii+1];
      }
      if (is_valid_poly(new_poly)) (*poly_count)++; 
    }
    if ((*poly_count) == 0) return -1;
    /*
    if (*poly_count == 1) {
      for (ii=0;ii<3;ii++) {
        if (dst_polys[0].verts[ii].x != src_poly->verts[ii].x ||
            dst_polys[0].verts[ii].y != src_poly->verts[ii].y)
          break;
      }
      if (ii == 3) return 0;
    }
    */
    return 1;
  }
  return 0;
}

/**
 * clips polys at viewport edges 
 */
void clip_polys(poly_id *dst_ids, fpoly *dst_polys, 
                poly_id *src_ids, fpoly *src_polys,
                int *poly_count) {
  int i, idx, idx_top;
  int idx_stack[0x4000];
  int dst_count;
  fpoly *poly;
  poly_id *poly_id;
  fpoly clipped[2];
  int count, res;
  
  idx_top=0;
  for (i=(*poly_count)-1;i>=0;i--)
    idx_stack[idx_top++] = i;
  
  dst_count=0;
  while (idx_top) {
    idx = idx_stack[--idx_top];
    if (idx < 0) {
      poly = &dst_polys[-idx-1];
      poly_id = &dst_ids[-idx-1];
    }
    else {
      poly = &src_polys[idx];
      poly_id = &src_ids[idx];
    }
    res = clip_poly(poly, &clipped[0], &count);
    if (res == 1) { // poly was clipped
      if (idx < 0)
        idx = -idx-1;
      else
        idx = dst_count++;
      dst_polys[idx] = clipped[0];
      dst_ids[idx] = *poly_id;
      idx_stack[idx_top++] = -idx-1;
      if (count == 2) {
        dst_polys[dst_count] = clipped[1];
        dst_ids[dst_count] = *poly_id;
        idx_stack[idx_top++] = -dst_count-1;
        dst_count++;
      }
    }
    else if (res == 0) {
      dst_polys[dst_count] = *poly;
      dst_ids[dst_count] = *poly_id;
      dst_count++;
    }
  }
  *poly_count = dst_count;
}
  
