void draw_polys_zbuf(poly_id *poly_ids, fpoly *polys, 
                     int poly_count, 
                     int w, int h, z_struct *z_buf) {
  int i, idx, x, y;
  fpoly *poly;
  float x0,y0,z0,x1,y1,z1,x2,y2,z2,w0,w1,w2;
  double x10,x21,x02,y10,y21,y02;
  double ad,bd,gd;
  double a,b,g;
  int xmin,ymin,xmax,ymax;
  int diffx;
  double det[3];
  float z;
  
  for (i=0;i<poly_count;i++) {
    poly = &polys[i];
    
    #define load_vert(vx,vy,vz,v) vx=(v.x+1)*(w/2);vy=(1-v.y)*(h/2);vz=v.z;
    load_vert(x0,y0,z0,poly->verts[0]);
    load_vert(x1,y1,z1,poly->verts[1]);
    load_vert(x2,y2,z2,poly->verts[2]);
    w0=poly->vertuvws[0].z;
    w1=poly->vertuvws[1].z;
    w2=poly->vertuvws[2].z;

	//if (poly->pad1 == 1)
	//	continue;
    if ((z0+z1+z2) < 9000.0)
        continue;
       
    x10 = x1 - x0; // v1 - v0
    y10 = y1 - y0; 
    x21 = x2 - x1; // v2 - v1
    y21 = y2 - y1; 
    x02 = x0 - x2; // v0 - v2
    y02 = y0 - y2; 
    
    xmin = (int)min(min(x0,x1),x2);
    xmax = (int)max(max(x0,x1),x2);
    ymin = (int)min(min(y0,y1),y2);
    ymax = (int)max(max(y0,y1),y2);
    
    det[0] = x0*y1 - x1*y0;
    det[1] = x1*y2 - x2*y1;
    det[2] = x2*y0 - x0*y2;    
    //if (det[0]+det[1]+det[2]<0)
    //  continue;
    
    #define g_nd(vx,vy) (x10*vy - y10*vx + det[0])
    #define a_nd(vx,vy) (x21*vy - y21*vx + det[1])
    #define b_nd(vx,vy) (x02*vy - y02*vx + det[2])
    
    ad = a_nd(x0,y0);
    bd = b_nd(x1,y1);
    gd = g_nd(x2,y2);
    a = a_nd(xmin,ymax)/ad;
    b = b_nd(xmin,ymax)/bd;
    g = g_nd(xmin,ymax)/gd;

    diffx = xmax - xmin;
    x10 /= ad; 
    y10 /= ad;
    x21 /= bd; 
    y21 /= bd;
    x02 /= gd; 
    y02 /= gd;
    x10 -= (y10*diffx);
    x21 -= (y21*diffx);
    x02 -= (y02*diffx);
    
    for (y=ymax;y>ymin;y--) { // top to bottom
      for (x=xmin;x<xmax;x++) { // left to right            
        if (a >= -0.01 && b >= -0.01 && g >= -0.01) {
          z = ((z0*(a/w0)) + 
               (z1*(b/w1)) + 
               (z2*(g/w2))) /
               ((a/w0)+(b/w1)+(g/w2));
 
          if (gfx_bounds_test(x, y, w, h)) {
            idx = gfx_pixel_idx(x, y, w, h)/3;
            if (z > 0.0 && (!z_buf[idx].draw_count || z_buf[idx].z >= z)) {
              z_buf[idx].z = z;
              z_buf[idx].poly_id = poly_ids[i];
              z_buf[idx].draw_count++;
            }
          }
        }
        a -= y21;
        b -= y02;
        g -= y10;
      }
      a -= x21;  
      b -= x02;
      g -= x10;
    }
  }
}

#define poly_id_val(p) (*(uint16_t*)&(p))
#define poly_ids_eq(a,b) (poly_id_val(a)==poly_id_val(b))

z_struct z_buf[512*512];
fpoly *poly_map[0x8000];
int draw_count_map[0x8000];
poly_id poly_id_buf[8192], ids_clipped[8192];
fpoly poly_buf[8192], polys_clipped[8192];

// filters polys/poly ids by visibility (neither occluded nor clipped)
// can only be used after polys have been projected
void compute_visible_polys(poly_id *poly_ids, fpoly *polys, 
                           int *poly_count, 
                           int w, int h) {
  int i;
  int z_buf_len;
  poly_id poly_id;
  int poly_id_val;
  fpoly *poly;
  int draw_count;
  
  memset(&z_buf, 0, sizeof(z_buf));
  memset(&poly_map, 0, sizeof(poly_map));
  memset(&draw_count_map, 0, sizeof(draw_count_map));
  memcpy(&poly_id_buf, poly_ids, sizeof(poly_id)*(*poly_count));
  memcpy(&poly_buf, polys, sizeof(fpoly)*(*poly_count));
  for (i=0;i<*poly_count;i++) {
    poly_id = poly_id_buf[i];
    poly_id_val = poly_id_val(poly_id);
    poly_map[poly_id_val] = &poly_buf[i];
  }
  
  // clip polys first, otherwise wastes rasterize time
  clip_polys(ids_clipped, polys_clipped, poly_ids, polys, poly_count);
  draw_polys_zbuf(ids_clipped, polys_clipped, *poly_count, w, h, z_buf);
  //draw_polys_zbuf(poly_ids, polys, *poly_count, w, h, z_buf);
  
  *poly_count = 0;
  z_buf_len = w*h;
  for (i=0;i<z_buf_len;i++) {
    if (!z_buf[i].draw_count) continue;
    poly_id = z_buf[i].poly_id;
    poly_id_val = poly_id_val(poly_id);
    draw_count = draw_count_map[poly_id_val]++;
    if (draw_count != 1) continue; // already drawn more than once or not drawn at least once yet
    if (poly = poly_map[poly_id_val]) { // 
      polys[(*poly_count)] = *poly;
      poly_ids[(*poly_count)++] = poly_id;
    }
  }
}

unsigned int *get_zbuf_image(unsigned int *buf, int w, int h, int scale) {
  int i, size;
  int offset;
  z_struct *z_struct;
  unsigned int color, r, g, b;
  
  size = w*h;
  for (i=0;i<size;i++) {
    z_struct = &z_buf[i];
    if (z_struct->draw_count) { 
      offset = (int)((z_struct->z) / scale);
      r = offset + z_struct->draw_count*5;
      g = offset + z_struct->draw_count*7;
      b = offset + z_struct->draw_count*10;
      color = (r << 24) | (g << 16) | (b << 8) | (255);
    }
    else
      color = 0;
    buf[i] = color;
  }
  
  return buf;
}


